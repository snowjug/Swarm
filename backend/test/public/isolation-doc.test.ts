import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { policyFor } from '../../src/auth/policy.js';
import { PUBLIC_REFUSED_ROUTES, PUBLIC_ROUTE_POLICY } from '../../src/public/guard.js';
import { publicApp, type PublicHarness } from '../support/public-idp.js';

/**
 * `docs/public/ISOLATION.md` lists every route the server registers and what keeps one person out of another's data
 * through it. It is generated from the same registry that `isolation.test.ts` is generated from, and this test fails if
 * the document and the server disagree, so that a route cannot be added without being in it.
 * `UPDATE_ISOLATION_DOC=1 npx vitest run backend/test/public/isolation-doc.test.ts` writes it again.
 */
const FILE = fileURLToPath(new URL('../../../docs/public/ISOLATION.md', import.meta.url));

let h: PublicHarness;
beforeAll(async () => {
  h = await publicApp();
});
afterAll(async () => {
  await h.close();
});

type Kind = 'public' | 'signed-in' | 'workspace' | 'project' | 'platform' | 'refused' | 'not-api';

const WHY: Record<Kind, { rule: string; proof: string }> = {
  public: {
    rule: 'Holds nothing of any person: a status, a document, a sign-in step, or a switch that needs its own key.',
    proof: '`auth.test.ts`, `freetier.test.ts`',
  },
  'signed-in': {
    rule: 'Answers with the caller’s own data only. What is read is chosen by the session, and no request value names a person or a workspace.',
    proof: '`isolation.test.ts` (own account, usage, audit trail, lists)',
  },
  workspace: {
    rule: 'Acts in the caller’s workspace, which is the session’s. A request cannot name another one, and a new project is always the caller’s.',
    proof: '`isolation.test.ts` (lists, comparisons, no workspace chosen by a body)',
  },
  project: {
    rule: 'Answered as if the project did not exist when it is not the caller’s, the same answer as for an id that never existed. With the application’s checks removed, the database returns nothing of it.',
    proof:
      '`isolation.test.ts` (every project route as another person, then again with the checks removed), `rls.test.ts`',
  },
  platform: {
    rule: 'An administrator only (by verified address, read on every request). It reads usage rows and switches, never a project, and the database gives it no way to.',
    proof: '`isolation.test.ts` (the administrator as attacker), `freetier.test.ts`',
  },
  refused: {
    rule: 'Not available in the public edition: 404 whoever asks, before anything about the caller is read. Nobody is ever added to a workspace or a project.',
    proof: '`auth.test.ts` (members routes), `isolation.test.ts`',
  },
  'not-api': {
    rule: 'Not a data route: the page, the files it is made of, and the sign-in redirects.',
    proof: '`auth.test.ts`',
  },
};

function kindOf(method: string, url: string): Kind {
  if (PUBLIC_REFUSED_ROUTES.has(`${method} ${url}`)) return 'refused';
  if (!url.startsWith('/api')) return 'not-api';
  const found = PUBLIC_ROUTE_POLICY[`${method} ${url}`] ?? policyFor(method, url);
  if (!found) throw new Error(`No policy for ${method} ${url}`);
  return found.kind as Kind;
}

function document(): string {
  const routes = [
    ...new Map(
      h.built.routes
        .filter(({ method }) => method !== 'HEAD')
        .map(({ method, url }) => [`${method} ${url}`, { method, url }] as const),
    ).values(),
  ].sort((a, b) => a.url.localeCompare(b.url) || a.method.localeCompare(b.method));
  const counts = new Map<Kind, number>();
  const rows = routes.map(({ method, url }) => {
    const kind = kindOf(method, url);
    counts.set(kind, (counts.get(kind) ?? 0) + 1);
    return `| \`${method} ${url}\` | ${kind} |`;
  });
  const lines = [
    '# Isolation: every route, and what keeps one person out of another’s data',
    '',
    'Generated by `backend/test/public/isolation-doc.test.ts` from the routes the server registers in the public edition',
    '(`UPDATE_ISOLATION_DOC=1 npx vitest run backend/test/public/isolation-doc.test.ts` writes it again). The same registry',
    'generates `isolation.test.ts`, which runs an attack on every project route and then again with the application-level checks',
    'taken away, so that what is left is the database (row-level security). A route that is added is in both without',
    'anyone remembering to add it. How the isolation is built is in [DESIGN.md](DESIGN.md), section 5.',
    '',
    `${routes.length} routes. By access: ${[...counts.entries()]
      .sort((a, b) => a[0].localeCompare(b[0]))
      .map(([kind, count]) => `${kind} ${count}`)
      .join(', ')}.`,
    '',
    '## What each kind of route is held by',
    '',
    '| Access | What keeps one person out of another’s data | Proved by |',
    '| ------ | ------------------------------------------- | --------- |',
    ...(Object.keys(WHY) as Kind[]).map(
      (kind) => `| ${kind} | ${WHY[kind].rule} | ${WHY[kind].proof} |`,
    ),
    '',
    '## Every route',
    '',
    '| Route | Access |',
    '| ----- | ------ |',
    ...rows,
    '',
  ];
  return lines.join('\n');
}

/** Whitespace in a table is not content: a formatter may pad it. */
const normalise = (text: string): string =>
  text
    .split('\n')
    .map((line) =>
      line
        .trim()
        .replace(/\s*\|\s*/gu, '|')
        .replace(/-{3,}/gu, '---'),
    )
    .join('\n')
    .trim();

describe('the document of every route and what isolates it', () => {
  it('lists every route the server registers, and nothing it does not', () => {
    const wanted = document();
    if (process.env.UPDATE_ISOLATION_DOC === '1') writeFileSync(FILE, wanted);
    const committed = readFileSync(FILE, 'utf8');
    expect(normalise(committed)).toBe(normalise(wanted));
  });

  it('has no route the guard does not know, and the registry is not small', () => {
    const text = document();
    expect(text).toContain('`POST /api/projects`');
    expect(text).toContain('`GET /api/projects/:id`');
    expect(text.split('\n').filter((line) => line.startsWith('| `')).length).toBeGreaterThan(100);
  });
});
