import { useState } from 'react';
import { ArrowRight, Radio, Square, Users } from 'lucide-react';
import type { ConsoleStep, ExecutionStep, Platform } from '../../../../shared/guided';
import type { ProjectDetail } from '../../../../shared/types';
import { actionLabel, isBusy, isGuided, platformNames, stepStatus } from '../../lib/console';
import { percent, signed } from '../../lib/format';
import type { Inspection } from '../../lib/graph';
import { EmptyPanel, Notice } from '../ui';
import { Citations } from './Citations';
import { MemoryStream } from './MemoryStream';
import { RunStepButton, StageStatus } from './StageControls';

function LegacyRounds({
  project,
  onInspect,
}: {
  project: ProjectDetail;
  onInspect: (selection: Inspection) => void;
}) {
  return (
    <section className="stage-card">
      <h3>Recorded quick-run rounds</h3>
      <p className="field-help">
        One original run using the saved {project.settings.network} network. Guided platform runs,
        memory IDs and scenario-minute clocks were not recorded.
      </p>
      {project.rounds.map((round) => (
        <details className="legacy-round record-details" key={round.round}>
          <summary>
            Round {round.round}{' '}
            <span className="mono">
              {round.activityCount} ACTIONS · {round.interactions} INTERACTIONS
            </span>
          </summary>
          <div className="stats-grid">
            <div>
              <span className="mono">MEAN POSITION</span>
              <strong>{signed(round.meanOpinion)}</strong>
            </div>
            <div>
              <span className="mono">SUPPORT SHARE</span>
              <strong>{percent(round.supportShare)}</strong>
            </div>
            <div>
              <span className="mono">OPPOSITION</span>
              <strong>{percent(round.oppositionShare)}</strong>
            </div>
            <div>
              <span className="mono">POLARIZATION</span>
              <strong>{round.polarization.toFixed(2)}</strong>
            </div>
          </div>
          {round.intervention && (
            <Notice tone="warning" title="Recorded intervention assumption">
              {round.intervention.label}
            </Notice>
          )}
          {round.actions.map((action) => (
            <article className="memory-record" key={action.id}>
              <span className="eyebrow">
                {actionLabel(action.type, project.mode === 'local')} · {action.id}
              </span>
              <h4>
                {project.agents.find((agent) => agent.id === action.agentId)?.name ??
                  action.agentId}
              </h4>
              <p className="preserve-text">{action.content}</p>
              <small className="mono">
                POSITION {signed(action.opinion)} · PEERS {action.peerIds.join(', ') || 'NONE'}
              </small>
              <Citations sourceIds={action.sourceIds} onInspect={onInspect} />
            </article>
          ))}
        </details>
      ))}
      {!project.rounds.length && (
        <EmptyPanel title="No rounds recorded">
          This quick run has no saved simulation output.
        </EmptyPanel>
      )}
    </section>
  );
}

export function SimulationStage({
  project,
  busy,
  onRun,
  onNavigate,
  onCancel,
  onInspect,
}: {
  project: ProjectDetail;
  busy: boolean;
  onRun: (step: ExecutionStep) => void;
  onNavigate: (step: ConsoleStep) => void;
  onCancel: () => void;
  onInspect: (selection: Inspection) => void;
}) {
  const guided = isGuided(project);
  const platforms = project.console?.platforms ?? [];
  const available = platforms.map((platform) => platform.platform);
  const [selected, setSelected] = useState<Platform>('plaza');
  const platform = available.includes(selected) ? selected : (available[0] ?? 'plaza');
  const ready = stepStatus(project, 'simulation') === 'ready';
  const simulationBusy =
    isBusy(project) && ['queued', 'running'].includes(stepStatus(project, 'simulation') ?? '');
  const local = project.mode === 'local';
  return (
    <div className="stage-content view-stack">
      <div>
        <span className="eyebrow">03 / SIMULATION</span>
        <h2>Observe recorded behavior</h2>
      </div>
      <StageStatus project={project} step="simulation" />
      <Notice
        title={
          local ? 'Rule-engine changes, not social posts' : 'Fictional model-assisted activity'
        }
      >
        {local
          ? 'Local update and observe events are numeric state transitions under deterministic rules. They are not language-model reasoning, conversations or real social activity.'
          : 'Recorded post / reply actions are generated by real provider calls for fictional proxies. They are neither actual public posts nor calibrated audience predictions.'}{' '}
        Platform positions are scenario state, not measured public opinion.
      </Notice>
      <div className="stage-actions">
        <RunStepButton
          project={project}
          step="simulation"
          busy={busy}
          onRun={onRun}
          label="Start Simulation"
        />
        {simulationBusy && (
          <button className="button button-danger" type="button" disabled={busy} onClick={onCancel}>
            <Square size={13} /> Cancel simulation
          </button>
        )}
      </div>
      {guided ? (
        <>
          <div className="platform-summary-grid">
            {(['plaza', 'community'] as const).map((id) => {
              const run = platforms.find((item) => item.platform === id);
              const last = run?.rounds.at(-1);
              const actions = run?.rounds.reduce((sum, round) => sum + round.actions.length, 0);
              return (
                <section
                  className={`platform-summary ${platform === id && run ? 'selected' : ''}`}
                  key={id}
                >
                  <div className="section-heading">
                    {id === 'plaza' ? <Radio size={18} /> : <Users size={18} />}
                    <span className={`mono platform-status ${run?.status ?? ''}`}>
                      {run?.status ?? 'NOT RECORDED'}
                    </span>
                  </div>
                  <h3>{platformNames[id]}</h3>
                  <p className="mono muted">
                    {run?.network ?? (id === 'plaza' ? 'broadcast' : 'community')} NETWORK
                  </p>
                  {run ? (
                    <>
                      {run.label !== platformNames[id] && <p className="field-help">{run.label}</p>}
                      <dl>
                        <div>
                          <dt>Round</dt>
                          <dd>
                            {run.currentRound} / {project.settings.rounds}
                          </dd>
                        </div>
                        <div>
                          <dt>Scenario minutes</dt>
                          <dd>{run.elapsedMinutes}</dd>
                        </div>
                        <div>
                          <dt>Recorded actions</dt>
                          <dd>{actions}</dd>
                        </div>
                        <div>
                          <dt>Latest mean position</dt>
                          <dd>{last ? signed(last.meanOpinion) : 'Not recorded'}</dd>
                        </div>
                      </dl>
                      <button
                        className="text-button"
                        type="button"
                        aria-pressed={platform === id}
                        onClick={() => setSelected(id)}
                      >
                        Inspect stream <ArrowRight size={13} />
                      </button>
                    </>
                  ) : (
                    <p className="field-help">
                      {project.console?.environment?.platforms.includes(id)
                        ? 'Selected in the environment; no platform run has been returned yet.'
                        : 'No run was recorded for this platform. Enable it in Environment Setup before simulation starts.'}
                    </p>
                  )}
                </section>
              );
            })}
          </div>
          {available.length ? (
            <div>
              <div
                className="segmented stream-tabs"
                role="group"
                aria-label="Recorded platform stream"
              >
                {available.map((id) => (
                  <button
                    type="button"
                    key={id}
                    aria-pressed={platform === id}
                    onClick={() => setSelected(id)}
                  >
                    {platformNames[id]}
                  </button>
                ))}
              </div>
              <MemoryStream
                key={platform}
                project={project}
                platform={platform}
                onInspect={onInspect}
              />
            </div>
          ) : (
            <EmptyPanel title="No platform runs recorded">
              Start Simulation after saving the environment. Platform streams and clocks are
              populated only from real server output.
            </EmptyPanel>
          )}
        </>
      ) : (
        <LegacyRounds project={project} onInspect={onInspect} />
      )}
      <div className="stage-actions">
        {ready && project.console?.steps.report === 'pending' && (
          <RunStepButton
            project={project}
            step="report"
            busy={busy}
            onRun={onRun}
            label="Generate Report"
          />
        )}
        {ready && project.console?.steps.report !== 'pending' && (
          <button
            className="button button-primary"
            type="button"
            onClick={() => onNavigate('report')}
          >
            Inspect report stage <ArrowRight size={14} />
          </button>
        )}
      </div>
      {guided && !ready && (
        <p className="field-help">
          Report generation unlocks only when simulation is ready. A cancelled or failed stage must
          be retried; no report is fabricated from a partial run.
        </p>
      )}
    </div>
  );
}
